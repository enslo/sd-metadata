import { describe, expect, it } from 'vitest';
import { parseKusArt } from '../../../src/parsers/kusart';

const COPYRIGHT = 'Generated by KusArt';

/** extra chunk as KusArt writes it: indented JSON ending in a newline */
function extra(fields: Record<string, unknown>): string {
  return `${JSON.stringify(
    {
      prompt: '1girl, solo',
      size: { height: 1024, width: 1024 },
      ...fields,
    },
    null,
    2,
  )}\n`;
}

describe('parseKusArt - Unit Tests', () => {
  it('should keep a task type missing from the model table as the model name', () => {
    const result = parseKusArt({
      Copyright: COPYRIGHT,
      extra: extra({ task_type: 'video_to_video' }),
    });

    expect(result.ok && result.value.model).toEqual({
      name: 'video_to_video',
    });
  });

  it('should read the model table whatever the case of the task type', () => {
    // KusArt's own table uses upper-case task types
    const result = parseKusArt({
      Copyright: COPYRIGHT,
      extra: extra({ task_type: 'TEXT_TO_IMAGE_NIJI' }),
    });

    expect(result.ok && result.value.model).toEqual({ name: 'Kusa-Niji' });
  });

  it('should leave the model out without a task type', () => {
    const result = parseKusArt({ Copyright: COPYRIGHT, extra: extra({}) });

    expect(result.ok).toBe(true);
    if (result.ok) {
      expect(result.value).not.toHaveProperty('model');
      expect(result.value).not.toHaveProperty('loras');
    }
  });

  it('should skip styles without an ID and read numeric IDs', () => {
    const result = parseKusArt({
      Copyright: COPYRIGHT,
      extra: extra({
        styles: [
          { style_id: '', priority: 1, weight: 1 },
          { priority: 2, weight: 1 },
          { style_id: 115, priority: 3, weight: 0.5 },
        ],
      }),
    });

    expect(result.ok && result.value.loras).toEqual([
      { name: 'Style 115', weight: 0.5 },
    ]);
  });

  it('should read the extra JSON from UserComment (JPEG/WebP)', () => {
    const result = parseKusArt({
      UserComment: JSON.stringify({
        Copyright: COPYRIGHT,
        extra: extra({ negative_prompt: 'lowres', style_id: '14' }),
      }),
    });

    expect(result.ok).toBe(true);
    if (result.ok) {
      expect(result.value.negativePrompt).toBe('lowres');
      expect(result.value.loras).toEqual([{ name: 'Style 14' }]);
    }
  });

  it('should return an error without a valid extra JSON object', () => {
    expect(parseKusArt({ Copyright: COPYRIGHT }).ok).toBe(false);
    expect(parseKusArt({ Copyright: COPYRIGHT, extra: '{"prompt": ' }).ok).toBe(
      false,
    );
    expect(parseKusArt({ Copyright: COPYRIGHT, extra: '["a"]' }).ok).toBe(
      false,
    );
  });
});
