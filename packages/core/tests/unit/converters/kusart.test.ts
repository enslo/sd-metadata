import { describe, expect, it } from 'vitest';
import {
  convertKusArtPngToSegments,
  convertKusArtSegmentsToPng,
} from '../../../src/converters/kusart';
import type { MetadataSegment, PngTextChunk } from '../../../src/types';

/** iTXt chunk as KusArt writes it */
function itxt(keyword: string, text: string): PngTextChunk {
  return {
    type: 'iTXt',
    keyword,
    compressionFlag: 0,
    compressionMethod: 0,
    languageTag: '',
    translatedKeyword: '',
    text,
  };
}

// Indented JSON ending in a newline, with Go's escaping of "<" and ">"
const EXTRA =
  '{\n  "prompt": "1girl, \\u003clora:x:1\\u003e, #テスト",\n  "task_type": "text_to_image"\n}\n';

describe('KusArt converter', () => {
  it('should pack both chunks into a UserComment JSON, keeping their text', () => {
    const segments = convertKusArtPngToSegments([
      itxt('extra', EXTRA),
      itxt('Copyright', 'Generated by KusArt'),
    ]);

    expect(segments).toEqual([
      {
        source: { type: 'exifUserComment' },
        data: JSON.stringify({
          extra: EXTRA,
          Copyright: 'Generated by KusArt',
        }),
      },
    ]);
  });

  it('should restore both chunks as iTXt, in order', () => {
    const segments: MetadataSegment[] = [
      {
        source: { type: 'exifUserComment' },
        data: JSON.stringify({
          extra: EXTRA,
          Copyright: 'Generated by KusArt',
        }),
      },
    ];

    expect(convertKusArtSegmentsToPng(segments)).toEqual([
      itxt('extra', EXTRA),
      itxt('Copyright', 'Generated by KusArt'),
    ]);
  });

  it('should restore no chunk without a UserComment JSON object', () => {
    expect(convertKusArtSegmentsToPng([])).toEqual([]);
    expect(
      convertKusArtSegmentsToPng([
        { source: { type: 'exifUserComment' }, data: 'not JSON' },
      ]),
    ).toEqual([]);
  });
});
