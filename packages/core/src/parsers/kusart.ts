import type { LoraSettings, StandardMetadata } from '../types';
import { Result } from '../types';
import { type EntryRecord, extractFromCommentJson } from '../utils/entries';
import { parseJson } from '../utils/json';
import { lora, optionalLoras, toWeight } from '../utils/lora';
import type { InternalParseResult } from './types';

/**
 * Fields of KusArt's `extra` JSON
 *
 * Only the request fields that reach the image are recorded: no sampler,
 * steps, CFG scale or seed.
 */
type KusArtExtra = Record<string, unknown>;

/**
 * Model of each task type, as KusArt's own generator maps them
 *
 * KusArt writes the task type in lower case and the table in upper case.
 */
const MODEL_BY_TASK_TYPE: Readonly<Record<string, string>> = {
  TEXT_TO_IMAGE: 'Kusa-XL',
  ANIMA_TEXT_TO_IMAGE: 'Kusa-Anima',
  TEXT_TO_IMAGE_EASY: 'Kusa-Easy',
  TEXT_TO_IMAGE_KUSA_MIX: 'Kusa-Mix',
  TEXT_TO_IMAGE_NIJI: 'Kusa-Niji',
  KREA2_TEXT_TO_IMAGE: 'Kusa-Krea2',
};

/**
 * Parse KusArt metadata from entries
 *
 * KusArt (formerly KusaPics) writes two iTXt chunks:
 * - `Copyright`: "Generated by KusArt"
 * - `extra`: JSON with the prompts, the size, the task type and the styles
 *
 * After conversion to JPEG/WebP both chunks are packed into one JSON
 * object in the EXIF UserComment.
 *
 * Styles are KusArt's LoRAs. Kusa-XL records the single style it always
 * applies as `style_id` and Kusa-Easy its styles as a `styles` list;
 * Kusa-Anima records none. Only internal IDs are recorded, not the names
 * KusArt shows.
 *
 * @param entries - Metadata entries
 * @returns Parsed metadata or error
 */
export function parseKusArt(entries: EntryRecord): InternalParseResult {
  const text = entries.extra ?? extractFromCommentJson(entries, 'extra');
  if (text === undefined) {
    return Result.error({ type: 'unsupportedFormat' });
  }

  const parsed = parseJson<KusArtExtra>(text);
  if (!parsed.ok || parsed.type !== 'object') {
    return Result.error({
      type: 'parseError',
      message: 'Invalid JSON in KusArt extra entry',
    });
  }
  const data = parsed.value;
  const size = isRecord(data.size) ? data.size : {};

  const metadata: Omit<StandardMetadata, 'raw'> = {
    software: 'kusart',
    prompt: toText(data.prompt) ?? '',
    negativePrompt: toText(data.negative_prompt) ?? '',
    width: toWeight(size.width) ?? 0,
    height: toWeight(size.height) ?? 0,
    ...optionalModel(toText(data.task_type)),
    ...optionalLoras(readStyles(data)),
  };

  return Result.ok(metadata);
}

/**
 * Model named after the task type
 *
 * A task type missing from the table is kept as the name: it still tells
 * which generator made the image.
 */
function optionalModel(
  taskType: string | undefined,
): Pick<StandardMetadata, 'model'> {
  if (!taskType) return {};
  const name = MODEL_BY_TASK_TYPE[taskType.toUpperCase()] ?? taskType;
  return { model: { name } };
}

/**
 * Read the styles as LoRAs named `Style <ID>`
 *
 * `styles` lists the styles of Kusa-Easy in priority order, each with a
 * weight; `style_id` is the single style of Kusa-XL, without one.
 */
function readStyles(data: KusArtExtra): LoraSettings[] {
  if (Array.isArray(data.styles)) {
    return data.styles.flatMap((style) => {
      const id = isRecord(style) ? toText(style.style_id) : undefined;
      if (!id) return [];
      return [lora({ name: `Style ${id}`, weight: toWeight(style.weight) })];
    });
  }

  const id = toText(data.style_id);
  return id ? [lora({ name: `Style ${id}` })] : [];
}

function isRecord(value: unknown): value is Record<string, unknown> {
  return typeof value === 'object' && value !== null && !Array.isArray(value);
}

/** Text of a JSON string or number */
function toText(value: unknown): string | undefined {
  if (typeof value === 'string') return value;
  if (typeof value === 'number') return String(value);
  return undefined;
}
